"""Prospective Stage 9 bee cue-reveal × wind factorial allocation.

All IDs/assignments generated by this repo are SYNTHETIC design QA only.
A real experiment must use a fresh, securely stored private seed with
prospectively sealed schedule and per-trial blinded release. Never use
the committed test seed as concealed real animal allocation.
"""
from __future__ import annotations
from collections import Counter,defaultdict
import argparse
import hashlib
import json
from pathlib import Path
import random

ORDERS=("handling_first","reward_first")
WINDS=("calm","crosswind")
SIDES=("left","right")
WIND_SEQUENCES=(("calm","crosswind","crosswind","calm"),
                ("crosswind","calm","calm","crosswind"))
BLOCK_TRIALS=16
TRIALS_PER_BEE=4*BLOCK_TRIALS
BEES_PER_COLONY=12
QA_SEED=20261029
CLOCK={"first_cue_s":2,"second_cue_s":4,"both_options_accessible_s":6,
       "evaluation_window_s":30}

def generate_allocation(n_colonies=24,bees_per_colony=BEES_PER_COLONY,seed=QA_SEED):
    """Counterbalance wind-block order, cue order, and reward side within bee."""
    if not (2<=n_colonies<=200 and 2<=bees_per_colony<=100):
        raise ValueError("NO_GO_ILLEGAL_COLONY_OR_BEE_RECRUITMENT")
    rng=random.Random(seed)
    records=[]
    for ci in range(n_colonies):
        colony=f"C{ci+1:03d}"
        for bi in range(bees_per_colony):
            bee=f"B{bi+1:03d}"
            seq=WIND_SEQUENCES[(ci+bi)%2]
            for block,wind in enumerate(seq,1):
                arm=[(order,side) for order in ORDERS
                     for side in SIDES for repeat in range(4)]
                rng.shuffle(arm)
                if len(arm)!=BLOCK_TRIALS:
                    raise AssertionError("trial factorial allocation not 16")
                for k,(order,side) in enumerate(arm,1):
                    records.append({
                        "trial_id":f"{colony}_{bee}_T{(block-1)*BLOCK_TRIALS+k:03d}",
                        "colony_id":colony,"bee_id":bee,
                        "block":block,"trial_in_block":k,
                        "assigned_wind":wind,
                        "assigned_cue_order":order,
                        "high_reward_and_difficult_handling_side":side,
                        "cue1_name":"reward" if order=="reward_first" else "handling",
                        "cue2_name":"handling" if order=="reward_first" else "reward",
                        **CLOCK})
    audit_allocation(records,expected_colonies=n_colonies,
                     expected_bees_per_colony=bees_per_colony)
    return records

def audit_allocation(rows,expected_colonies=None,
                     expected_bees_per_colony=None):
    """Fail closed on trial duplication, cluster imbalance, cue/gate violations."""
    if not rows:raise ValueError("NO_GO_EMPTY_STAGE9_ALLOCATION")
    trial_ids=[r["trial_id"] for r in rows]
    if len(set(trial_ids))!=len(trial_ids):
        raise ValueError("NO_GO_DUPLICATE_STAGE9_TRIAL_ASSIGNMENT")
    by_bee=defaultdict(list)
    by_colony=defaultdict(set)
    for r in rows:
        key=(r["colony_id"],r["bee_id"])
        by_bee[key].append(r)
        by_colony[r["colony_id"]].add(r["bee_id"])
        if (r["assigned_cue_order"] not in ORDERS or
            r["assigned_wind"] not in WINDS or
            r["high_reward_and_difficult_handling_side"] not in SIDES):
            raise ValueError("NO_GO_STAGE9_INVALID_FACTOR_LABEL")
        if not (r["first_cue_s"]==2 and r["second_cue_s"]==4
                and r["both_options_accessible_s"]==6
                and r["evaluation_window_s"]==30):
            raise ValueError("NO_GO_STAGE9_CUE_TIMING_DRIFT")
        should=("reward","handling") if r["assigned_cue_order"]=="reward_first" else (
            "handling","reward")
        if (r["cue1_name"],r["cue2_name"])!=should:
            raise ValueError("NO_GO_STAGE9_REVEAL_ORDER_INCONSISTENT")
    if expected_colonies is not None and len(by_colony)!=expected_colonies:
        raise ValueError("NO_GO_STAGE9_MISSING_COLONIES")
    if expected_bees_per_colony is not None and any(
        len(x)!=expected_bees_per_colony for x in by_colony.values()
    ):raise ValueError("NO_GO_STAGE9_UNBALANCED_BEE_RECRUITMENT")
    report={"synthetic_design_QA_only":True,
            "colonies":len(by_colony),
            "bees":len(by_bee),
            "trials":len(rows),
            "trials_per_bee":TRIALS_PER_BEE,
            "blocks_per_bee":4,
            "trials_per_block":BLOCK_TRIALS,
            "each_bee_trial_count_per_wind_cue_cell":16,
            "wind_conditions":WINDS,"cue_orders":ORDERS,
            "cue_and_access_clock_seconds":CLOCK,
            "colony_block_order_sequences":Counter()}
    cell=Counter()
    for (colony,bee),visits in by_bee.items():
        if len(visits)!=TRIALS_PER_BEE:
            raise ValueError("NO_GO_STAGE9_NOT_64_TRIALS_PER_BEE")
        blocks=defaultdict(list)
        for r in visits:blocks[r["block"]].append(r)
        if set(blocks)!={1,2,3,4}:
            raise ValueError("NO_GO_STAGE9_WRONG_BLOCK_COUNT")
        seq=[]
        for block in sorted(blocks):
            r=blocks[block]
            if len(r)!=BLOCK_TRIALS:
                raise ValueError("NO_GO_STAGE9_WRONG_BLOCK_TRIAL_COUNT")
            if set(x["trial_in_block"] for x in r)!=set(range(1,BLOCK_TRIALS+1)):
                raise ValueError("NO_GO_STAGE9_MISSING_TRIAL_WITHIN_BLOCK")
            wind={x["assigned_wind"] for x in r}
            if len(wind)!=1:
                raise ValueError("NO_GO_STAGE9_WIND_SWITCHED_MID_BLOCK")
            seq.append(next(iter(wind)))
            counts=Counter((x["assigned_cue_order"],
                            x["high_reward_and_difficult_handling_side"])
                           for x in r)
            if set(counts)!={(o,s) for o in ORDERS for s in SIDES} or any(
                n!=4 for n in counts.values()
            ):raise ValueError("NO_GO_STAGE9_ORDER_SIDE_NOT_BALANCED_IN_BLOCK")
        if tuple(seq) not in WIND_SEQUENCES:
            raise ValueError("NO_GO_STAGE9_WIND_BLOCK_CROSSOVER_SEQUENCE")
        report["colony_block_order_sequences"][str(seq)]+=1
        per_cell=Counter((r["assigned_wind"],r["assigned_cue_order"])
                         for r in visits)
        if set(per_cell)!={(w,o) for w in WINDS for o in ORDERS} or any(
            n!=16 for n in per_cell.values()
        ):raise ValueError("NO_GO_STAGE9_WIND_ORDER_NOT_BALANCED_PER_BEE")
        cell.update(per_cell)
    # A source colony has many individual bees; never replace colony units
    # with the total number of randomized trial rows.
    report["total_cell_counts"]={f"{w}__{o}":int(cell[w,o])
                                 for w in WINDS for o in ORDERS}
    report["colony_block_order_sequences"]=dict(
        report["colony_block_order_sequences"])
    report["analysis_independence_unit"]="independently recruited bee colony"
    return report

def allocation_commitment(rows):
    """Hash synthetic QA assignments without emitting exact future arms."""
    serialized=json.dumps(rows,sort_keys=True,ensure_ascii=True,
                          separators=(",",":")).encode("utf-8")
    return hashlib.sha256(serialized).hexdigest()

def generate_receipt(n_colonies=24,bees=12,seed=QA_SEED):
    rows=generate_allocation(n_colonies,bees,seed)
    qa=audit_allocation(rows,expected_colonies=n_colonies,
                        expected_bees_per_colony=bees)
    qa.update({
        "type":"synthetic_QA_schedule_receipt_no_real_bee_allocations",
        "allocation_sha256_commitment":allocation_commitment(rows),
        "QA_seed_fixed_public":seed,
        "private_allocation_seed_NOT_GENERATED_OR_STORED":True,
        "do_not_release_real_trial_arm_schedule":True,
        "real_study_requires_concealed_independent_allocation_before_outcomes":True
    })
    return qa

def main(argv=None):
    ap=argparse.ArgumentParser()
    ap.add_argument("--colonies",type=int,default=24)
    ap.add_argument("--bees",type=int,default=12)
    ap.add_argument("--seed",type=int,default=QA_SEED,
                    help="SYNTHETIC QA ONLY; real allocation needs separate private seed")
    ap.add_argument("--out",default="bee_stage9_design_output")
    args=ap.parse_args(argv)
    report=generate_receipt(args.colonies,args.bees,args.seed)
    out=Path(args.out)
    out.mkdir(parents=True,exist_ok=True)
    (out/"cue_order_wind_randomization_qa_receipt.json").write_text(
        json.dumps(report,indent=2,ensure_ascii=False))
    print("STAGE9_SYNTHETIC_RANDOMIZATION_AUDIT "+
          json.dumps(report,ensure_ascii=False),flush=True)
    print("STAGE9_SYNTHETIC_ALLOCATION_READY_NO_ANIMAL_DATA",flush=True)

if __name__=="__main__":main()
